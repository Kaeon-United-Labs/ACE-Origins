import { serve, launch } from "./shot.mjs";
const server = await serve(); const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = []; page.on("pageerror", e => errors.push(e.message.slice(0, 200)));
await page.goto(`http://127.0.0.1:${server.address().port}/Build/index.html`);
await page.waitForFunction(() => window.origins && window.origins.frame > 2, null, { timeout: 60000 });
await page.waitForFunction(() => !document.getElementById("loading"), null, { timeout: 120000 });
await page.waitForTimeout(1500);
await page.keyboard.down("Enter"); await page.waitForTimeout(110); await page.keyboard.up("Enter");
await page.waitForFunction(() => window.origins.data.packages.game.properties.meta.data.mode === "play", null, { timeout: 60000 });
const pos = () => page.evaluate(() => window.origins.data.packages.player.properties.meta.data.position.map(v => +v.toFixed(1)));
const put = (x, y, z, yaw, pitch) => page.evaluate(([x, y, z, yaw, pitch]) => { const p = window.origins.data.packages.player.properties.meta.data; p.position = [x, y, z]; p.vel = [0,0,0]; p.vy = 0; p.flying = 1; p.yaw = yaw; p.pitch = pitch; p.tele = 5; }, [x, y, z, yaw, pitch]);
await put(10240, 20, 0, 0, 1.45); await page.waitForTimeout(3000);
await page.keyboard.down("KeyW"); await page.waitForTimeout(3500); await page.keyboard.up("KeyW");
console.log("straight up from below the tip, y=20 ->", JSON.stringify(await pos()), "(tip of the underside at y=62)");
await put(10240 + 140, 95, 0, Math.PI / 2, 0); await page.waitForTimeout(3000);
await page.keyboard.down("KeyW"); await page.waitForTimeout(3500); await page.keyboard.up("KeyW");
console.log("flew in at the side at y=95 from x+140 ->", JSON.stringify(await pos()), "(island centre x=10240)");
await put(10240 + 100, 180, 0, Math.PI / 2, -0.35); await page.waitForTimeout(3000);
await page.keyboard.down("KeyW"); await page.waitForTimeout(2800); await page.keyboard.up("KeyW");
console.log("flew down onto the top ->", JSON.stringify(await pos()), "(top y=132)");
// shots from outside
await put(10240 + 150, 100, 150, 0.785, -0.12); await page.waitForTimeout(4000);
await page.screenshot({ path: "../../Scratch/thumbs/sky-side.png" });
await put(10240 + 60, 40, 90, 0.5, 0.45); await page.waitForTimeout(4000);
await page.screenshot({ path: "../../Scratch/thumbs/sky-under.png" });
console.log("errors", errors);
await browser.close(); server.close();
