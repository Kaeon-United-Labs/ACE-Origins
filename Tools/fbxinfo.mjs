import fs from "node:fs";
import * as THREE from "three";
import { FBXLoader } from "three/examples/jsm/loaders/FBXLoader.js";
const b = fs.readFileSync(process.argv[2]);
const root = new FBXLoader().parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength), "");
const bones = []; root.traverse(o => { if (o.isBone) bones.push(o.name); });
console.log("bones", bones.length, bones.slice(0, 16).join(","));
console.log("clips", root.animations.length, root.animations.slice(0, 5).map(a => a.name + ":" + a.tracks.length + ":" + a.duration.toFixed(2)).join(" | "));
const idle = root.animations.find(a => /Idle_Loop/.test(a.name));
if (idle) console.log(idle.tracks.slice(0, 6).map(t => t.name + " " + t.values.length / t.times.length).join(" | "));
console.log("scale", root.scale.toArray(), root.children.map(c => c.name + ":" + c.type).join(","));
