import { serve, launch } from "./shot.mjs";
const server = await serve(); const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.goto(`http://127.0.0.1:${server.address().port}/Build/index.html`);
await page.waitForFunction(() => window.origins && window.origins.frame > 2, null, { timeout: 60000 });
await page.waitForFunction(() => !document.getElementById("loading"), null, { timeout: 120000 });
await page.waitForTimeout(1500);
await page.mouse.click(640, 360);
await page.keyboard.down("Enter"); await page.waitForTimeout(110); await page.keyboard.up("Enter");
await page.waitForFunction(() => window.origins.data.packages.game.properties.meta.data.mode === "play", null, { timeout: 60000 });
await page.evaluate(([yaw]) => { const r = window.origins.data.packages.rpg.properties.meta.data; r.found.town = 1; r.found.sky = 1; r.found.fort = 1; r.found.stones = 1; const p = window.origins.data.packages.player.properties.meta.data; p.position = [20500, 16, 4]; p.yaw = yaw; p.tele = 5; }, [+(process.env.YAW || 1)]);
await page.waitForTimeout(3500);
await page.keyboard.down(process.env.KEY || "KeyM"); await page.waitForTimeout(110); await page.keyboard.up(process.env.KEY || "KeyM");
await page.waitForTimeout(1200);
console.log(await page.evaluate(() => { const y = window.origins.data.packages.ui.packages.menu.packages.mapview.packages.you.properties.meta.data; const p = window.origins.data.packages.player.properties.meta.data; return JSON.stringify({ rot: y.rotation, yaw: p.yaw, pos: y.position }); }));
await page.mouse.move(100, 650);
await page.screenshot({ path: "../../Scratch/thumbs/map3-town-" + (process.env.YAW||"1") + ".png" });
for (let i = 0; i < 4; i++) { await page.mouse.move(640, 380); await page.mouse.wheel(0, -120); await page.waitForTimeout(180); }
await page.waitForTimeout(500);
await page.screenshot({ path: "../../Scratch/thumbs/map3-zoom.png" });
await browser.close(); server.close();
