// Records a CDP screencast while flying: node cast.mjs <prefix> <x> <y> <z> <yaw> <pitch> <seconds> [boost]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { serve, launch } from "./shot.mjs";
const here = path.dirname(fileURLToPath(import.meta.url));
const [prefix, x, y, z, yaw, pitch, seconds, boost] = process.argv.slice(2);
const out = path.join(here, "..", "..", "Scratch", "cast"); fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) if (f.startsWith(prefix + "-")) fs.unlinkSync(path.join(out, f));
const server = await serve(); const browser = await launch();
const page = await browser.newPage({ viewport: { width: 800, height: 450 } });
await page.goto(`http://127.0.0.1:${server.address().port}/Build/index.html`);
await page.waitForFunction(() => window.angaia && window.angaia.frame > 5, null, { timeout: 60000 });
await page.waitForTimeout(12000);
await page.mouse.click(400, 225); await page.waitForTimeout(500);
await page.evaluate(([x, y, z, yaw, pitch]) => { const d = window.angaia.data.packages.player.properties.meta.data; d.position = [+x, +y, +z]; d.vel = [0, 0, 0]; d.yaw = +yaw; d.pitch = +pitch; d.flying = 1; }, [x, y, z, yaw, pitch]);
if (process.env.CAST_EVAL) await page.evaluate(process.env.CAST_EVAL);
await page.waitForTimeout(2500);
const client = await page.context().newCDPSession(page);
let n = 0; const times = [];
client.on("Page.screencastFrame", async ev => { fs.writeFileSync(path.join(out, `${prefix}-${String(n++).padStart(3, "0")}.jpg`), Buffer.from(ev.data, "base64")); times.push(ev.metadata.timestamp); await client.send("Page.screencastFrameAck", { sessionId: ev.sessionId }).catch(() => {}); });
await client.send("Page.startScreencast", { format: "jpeg", quality: 70, everyNthFrame: 1 });
await page.keyboard.down("KeyW"); if (boost) await page.keyboard.down("ShiftLeft");
await page.waitForTimeout(+seconds * 1000);
await client.send("Page.stopScreencast");
console.log("frames", n, "avg interval ms", n > 1 ? ((times[n - 1] - times[0]) / (n - 1) * 1000).toFixed(1) : "-");
await browser.close(); server.close();
