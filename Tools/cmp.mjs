import fs from "node:fs";
import * as THREE from "three";
import { FBXLoader } from "three/examples/jsm/loaders/FBXLoader.js";
const b = fs.readFileSync("../../Scratch/dl/ual/Animation Library[Standard]/Unreal Engine/AL_Standard.fbx");
const root = new FBXLoader().parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength), "");
const g = JSON.parse(fs.readFileSync("../../Scratch/dl/Universal Base Characters[Standard]/Base Characters/Godot - UE/Superhero_Male_FullBody.gltf", "utf8"));
const gn = {}; g.nodes.forEach(n => gn[n.name] = n);
let worst = 0; const rows = [];
root.traverse(o => {
	if (!o.isBone || !gn[o.name]) return;
	const q = gn[o.name].rotation || [0, 0, 0, 1];
	const d = Math.abs(o.quaternion.x * q[0] + o.quaternion.y * q[1] + o.quaternion.z * q[2] + o.quaternion.w * q[3]);
	const t = gn[o.name].translation || [0, 0, 0];
	rows.push([o.name, d.toFixed(4), o.position.toArray().map(v => v.toFixed(2)).join(","), t.map(v => v.toFixed(2)).join(",")]);
	worst = Math.max(worst, 1 - d);
});
console.log("worst rest-rotation mismatch (1 = identical dot):", (1 - worst).toFixed(4));
console.log(rows.slice(0, 8).map(r => r.join("  ")).join("\n"));
